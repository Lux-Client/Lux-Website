// Email + password accounts, 2FA (TOTP + recovery codes), passkeys and the email quota.
// Google accounts keep working: google_id becomes optional so email-only accounts can exist.

async function createAuthTables(connection) {
    await connection.query('ALTER TABLE users ALTER COLUMN google_id DROP NOT NULL');
    await connection.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS password_hash TEXT');
    await connection.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified BOOLEAN NOT NULL DEFAULT FALSE');
    await connection.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS totp_secret TEXT');
    await connection.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS totp_enabled BOOLEAN NOT NULL DEFAULT FALSE');
    await connection.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS totp_last_step BIGINT');
    await connection.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS failed_logins INTEGER NOT NULL DEFAULT 0');
    await connection.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS locked_until TIMESTAMPTZ');
    await connection.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS password_changed_at TIMESTAMPTZ');
    // Google already verified these addresses.
    await connection.query('UPDATE users SET email_verified = TRUE WHERE google_id IS NOT NULL AND email_verified IS NOT TRUE');
    await connection.query('CREATE INDEX IF NOT EXISTS idx_users_email ON users(email)');

    // One-time links sent by email: confirm address, reset password. Only the SHA-256 is stored.
    await connection.query(`
        CREATE TABLE IF NOT EXISTS auth_tokens (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            kind VARCHAR(20) NOT NULL,
            token_hash VARCHAR(64) UNIQUE NOT NULL,
            expires_at TIMESTAMPTZ NOT NULL,
            used_at TIMESTAMPTZ,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
    `);
    await connection.query('CREATE INDEX IF NOT EXISTS idx_auth_tokens_user ON auth_tokens(user_id)');

    await connection.query(`
        CREATE TABLE IF NOT EXISTS auth_recovery_codes (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            code_hash VARCHAR(64) NOT NULL,
            used_at TIMESTAMPTZ,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
    `);
    await connection.query('CREATE INDEX IF NOT EXISTS idx_auth_recovery_codes_user ON auth_recovery_codes(user_id)');

    await connection.query(`
        CREATE TABLE IF NOT EXISTS auth_passkeys (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            credential_id VARCHAR(512) UNIQUE NOT NULL,
            public_key TEXT NOT NULL,
            counter BIGINT NOT NULL DEFAULT 0,
            transports VARCHAR(200),
            name VARCHAR(60) NOT NULL DEFAULT 'Passkey',
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            last_used_at TIMESTAMPTZ
        )
    `);
    await connection.query('CREATE INDEX IF NOT EXISTS idx_auth_passkeys_user ON auth_passkeys(user_id)');

    // Sent emails per day ("d:2026-11-16") and per month ("m:2026-11"), UTC.
    await connection.query(`
        CREATE TABLE IF NOT EXISTS email_usage (
            period VARCHAR(16) PRIMARY KEY,
            sent INTEGER NOT NULL DEFAULT 0,
            blocked BOOLEAN NOT NULL DEFAULT FALSE,
            updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
    `);
}

module.exports = { createAuthTables };
