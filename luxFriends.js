/* Lux Client mod: friends, direct messages and server invites (like Discord, without voice).

   - Friends are Minecraft accounts that signed in with the Lux mod. A request goes out by
     Minecraft name; the other side accepts, declines or blocks.
   - Blocking ends the friendship, removes open requests and stops further requests and
     messages from that player. Muting only silences notifications (the mod reads the flag).
   - Online status lives in memory: the mod sends a heartbeat every few seconds with what it
     is doing (menu, singleplayer or the server's public name) and gets new messages back.
   - Invites: "come to my server" - only valid while the sender is still on that server.
   - Admins can ban a player from the whole social feature (lux_social_bans). */

const { rateLimit } = require('express-rate-limit');
const pool = require('./database');

const ONLINE_MS = 45 * 1000;
const MAX_FRIENDS = 300;
const MAX_OUTGOING = 50;
const MAX_TEXT = 500;
const PAGE = 50;
const KEEP_MESSAGES_MS = 180 * 86400000;
const UUID_RE = /^[0-9a-f]{32}$/;

const now = () => Date.now();
const cleanUuid = (v) => (typeof v === 'string' ? v.replace(/-/g, '').toLowerCase() : '');

async function createFriendTables(connection) {
    await connection.query(`
        CREATE TABLE IF NOT EXISTS lux_friends (
            a_uuid VARCHAR(32) NOT NULL,
            b_uuid VARCHAR(32) NOT NULL,
            created_at BIGINT NOT NULL DEFAULT 0,
            PRIMARY KEY (a_uuid, b_uuid)
        )
    `);
    await connection.query('CREATE INDEX IF NOT EXISTS idx_lux_friends_b ON lux_friends(b_uuid)');
    await connection.query(`
        CREATE TABLE IF NOT EXISTS lux_friend_requests (
            from_uuid VARCHAR(32) NOT NULL,
            to_uuid VARCHAR(32) NOT NULL,
            created_at BIGINT NOT NULL DEFAULT 0,
            PRIMARY KEY (from_uuid, to_uuid)
        )
    `);
    await connection.query('CREATE INDEX IF NOT EXISTS idx_lux_friend_requests_to ON lux_friend_requests(to_uuid)');
    // uuid blocked blocked_uuid / uuid muted muted_uuid
    await connection.query(`
        CREATE TABLE IF NOT EXISTS lux_blocks (
            uuid VARCHAR(32) NOT NULL,
            blocked_uuid VARCHAR(32) NOT NULL,
            created_at BIGINT NOT NULL DEFAULT 0,
            PRIMARY KEY (uuid, blocked_uuid)
        )
    `);
    await connection.query(`
        CREATE TABLE IF NOT EXISTS lux_mutes (
            uuid VARCHAR(32) NOT NULL,
            muted_uuid VARCHAR(32) NOT NULL,
            PRIMARY KEY (uuid, muted_uuid)
        )
    `);
    // kind: 'text' or 'invite' (body is then JSON {server, address})
    await connection.query(`
        CREATE TABLE IF NOT EXISTS lux_messages (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            from_uuid VARCHAR(32) NOT NULL,
            to_uuid VARCHAR(32) NOT NULL,
            kind VARCHAR(10) NOT NULL DEFAULT 'text',
            body TEXT NOT NULL,
            read BOOLEAN NOT NULL DEFAULT FALSE,
            created_at BIGINT NOT NULL DEFAULT 0
        )
    `);
    await connection.query('CREATE INDEX IF NOT EXISTS idx_lux_messages_to ON lux_messages(to_uuid, id)');
    await connection.query('CREATE INDEX IF NOT EXISTS idx_lux_messages_pair ON lux_messages(from_uuid, to_uuid)');
    // Banned from friends, chat and invites (by an admin).
    await connection.query(`
        CREATE TABLE IF NOT EXISTS lux_social_bans (
            uuid VARCHAR(32) PRIMARY KEY,
            reason VARCHAR(200),
            banned_by VARCHAR(100),
            created_at BIGINT NOT NULL DEFAULT 0
        )
    `);
}

/**
 * Adds the friend routes to the Lux router. ctx brings what luxCosmetics.js already has:
 * requireMod (mod token -> lux_players row), requireAdmin, audit, wrap, HttpError.
 */
function attachFriends(router, ctx) {
    const { requireMod, requireAdmin, audit, wrap, HttpError } = ctx;

    /** uuid -> { kind, version, server, address, at } */
    const presence = new Map();
    /** social ban cache: uuid -> { banned, until } */
    const banCache = new Map();

    const limiter = (limit) => rateLimit({
        windowMs: 60 * 1000,
        limit,
        standardHeaders: true,
        legacyHeaders: false,
        handler: (req, res) => res.status(429).json({ error: 'Too many requests - please wait a moment.' })
    });
    const pollLimiter = limiter(150);
    const actionLimiter = limiter(40);
    const messageLimiter = limiter(30);

    const pair = (x, y) => (x < y ? [x, y] : [y, x]);

    async function banOf(uuid) {
        const c = banCache.get(uuid);
        if (c && c.until > now()) return c.ban;
        const [rows] = await pool.query('SELECT reason, created_at FROM lux_social_bans WHERE uuid = ?', [uuid]);
        const ban = rows[0] ? { reason: rows[0].reason || null, at: Number(rows[0].created_at) } : null;
        banCache.set(uuid, { ban, until: now() + 30000 });
        return ban;
    }

    async function requireSocial(req) {
        const p = await requireMod(req);
        const ban = await banOf(p.uuid);
        if (ban) throw new HttpError(403, ban.reason ? `You are banned from friends and chat: ${ban.reason}` : 'You are banned from friends and chat.');
        return p;
    }

    async function areFriends(x, y) {
        const [a, b] = pair(x, y);
        const [rows] = await pool.query('SELECT 1 AS ok FROM lux_friends WHERE a_uuid = ? AND b_uuid = ?', [a, b]);
        return rows.length > 0;
    }

    async function blocked(by, who) {
        const [rows] = await pool.query('SELECT 1 AS ok FROM lux_blocks WHERE uuid = ? AND blocked_uuid = ?', [by, who]);
        return rows.length > 0;
    }

    async function player(uuid) {
        const [rows] = await pool.query('SELECT uuid, name FROM lux_players WHERE uuid = ?', [uuid]);
        return rows[0] || null;
    }

    function target(req) {
        const uuid = cleanUuid((req.params && req.params.uuid) || (req.body && req.body.uuid));
        if (!UUID_RE.test(uuid)) throw new HttpError(400, 'Invalid player.');
        return uuid;
    }

    async function online(uuid) {
        const p = presence.get(uuid);
        if (!p || p.at < now() - ONLINE_MS) return null;
        if (await banOf(uuid)) return null;
        return p;
    }

    function activity(p) {
        return p ? { kind: p.kind, version: p.version, server: p.server } : null;
    }

    async function friendList(me) {
        const [rows] = await pool.query(
            `SELECT f.a_uuid, f.b_uuid, f.created_at, p.uuid, p.name FROM lux_friends f
             JOIN lux_players p ON p.uuid = (CASE WHEN f.a_uuid = ? THEN f.b_uuid ELSE f.a_uuid END)
             WHERE f.a_uuid = ? OR f.b_uuid = ?`,
            [me, me, me]
        );
        const [mutes] = await pool.query('SELECT muted_uuid FROM lux_mutes WHERE uuid = ?', [me]);
        const muted = new Set(mutes.map((m) => m.muted_uuid));
        const [unread] = await pool.query(
            'SELECT from_uuid, COUNT(*) AS n, MAX(id) AS last FROM lux_messages WHERE to_uuid = ? AND read = FALSE GROUP BY from_uuid',
            [me]
        );
        const unreadBy = new Map(unread.map((u) => [u.from_uuid, Number(u.n)]));
        const [lastRows] = await pool.query(
            `SELECT CASE WHEN from_uuid = ? THEN to_uuid ELSE from_uuid END AS other, MAX(created_at) AS at
             FROM lux_messages WHERE from_uuid = ? OR to_uuid = ? GROUP BY 1`,
            [me, me, me]
        );
        const lastAt = new Map(lastRows.map((r) => [r.other, Number(r.at)]));
        const out = [];
        for (const r of rows) {
            const p = await online(r.uuid);
            out.push({
                uuid: r.uuid,
                name: r.name,
                online: !!p,
                activity: activity(p),
                muted: muted.has(r.uuid),
                unread: unreadBy.get(r.uuid) || 0,
                lastMessageAt: lastAt.get(r.uuid) || 0,
                since: Number(r.created_at),
            });
        }
        out.sort((x, y) => (y.online - x.online) || (y.lastMessageAt - x.lastMessageAt) || x.name.localeCompare(y.name));
        return out;
    }

    async function requestLists(me) {
        const [incoming] = await pool.query(
            'SELECT r.from_uuid AS uuid, p.name, r.created_at FROM lux_friend_requests r JOIN lux_players p ON p.uuid = r.from_uuid WHERE r.to_uuid = ? ORDER BY r.created_at DESC',
            [me]
        );
        const [outgoing] = await pool.query(
            'SELECT r.to_uuid AS uuid, p.name, r.created_at FROM lux_friend_requests r JOIN lux_players p ON p.uuid = r.to_uuid WHERE r.from_uuid = ? ORDER BY r.created_at DESC',
            [me]
        );
        const [blocks] = await pool.query(
            'SELECT b.blocked_uuid AS uuid, p.name FROM lux_blocks b JOIN lux_players p ON p.uuid = b.blocked_uuid WHERE b.uuid = ? ORDER BY p.name',
            [me]
        );
        const map = (r) => ({ uuid: r.uuid, name: r.name, at: Number(r.created_at || 0) });
        return { incoming: incoming.map(map), outgoing: outgoing.map(map), blocked: blocks.map((b) => ({ uuid: b.uuid, name: b.name })) };
    }

    async function makeFriends(x, y) {
        const [a, b] = pair(x, y);
        await pool.query('INSERT INTO lux_friends (a_uuid, b_uuid, created_at) VALUES (?, ?, ?) ON CONFLICT (a_uuid, b_uuid) DO NOTHING RETURNING a_uuid',
            [a, b, now()]);
        await pool.query('DELETE FROM lux_friend_requests WHERE (from_uuid = ? AND to_uuid = ?) OR (from_uuid = ? AND to_uuid = ?)', [x, y, y, x]);
    }

    async function unfriend(x, y) {
        const [a, b] = pair(x, y);
        await pool.query('DELETE FROM lux_friends WHERE a_uuid = ? AND b_uuid = ?', [a, b]);
    }

    function messageOut(m, me) {
        const out = {
            id: Number(m.id),
            from: m.from_uuid,
            to: m.to_uuid,
            mine: m.from_uuid === me,
            kind: m.kind,
            at: Number(m.created_at),
            read: !!m.read,
        };
        if (m.kind === 'invite') {
            let inv = {};
            try {
                inv = JSON.parse(m.body);
            } catch {
                inv = {};
            }
            out.server = inv.server || null;
            out.address = inv.address || null;
            const p = presence.get(m.from_uuid);
            // Valid while the sender is still on that server (and online).
            out.active = !!(p && p.at >= now() - ONLINE_MS && p.kind === 'server' && p.address && p.address === inv.address
                && Number(m.created_at) >= (p.joined || 0));
        } else {
            out.text = m.body;
        }
        return out;
    }

    // ------------------------------------------------------------------ overview + heartbeat

    router.get('/friends', wrap(async (req, res) => {
        const p = await requireMod(req);
        const ban = await banOf(p.uuid);
        if (ban) return res.json({ banned: true, reason: ban.reason, friends: [], incoming: [], outgoing: [], blocked: [] });
        res.json({ banned: false, friends: await friendList(p.uuid), ...(await requestLists(p.uuid)) });
    }));

    /**
     * Heartbeat (every few seconds while the game runs): what the player is doing right now.
     * Body: { kind: 'menu'|'single'|'server', version, server (public name or null), address, since (last message id seen) }
     * Answer: new incoming messages since `since`, open request count, unread total.
     */
    router.post('/friends/poll', pollLimiter, wrap(async (req, res) => {
        const p = await requireMod(req);
        const ban = await banOf(p.uuid);
        if (ban) return res.json({ banned: true, reason: ban.reason, messages: [], requests: 0, unread: 0 });
        const b = req.body || {};
        const kind = ['menu', 'single', 'server'].includes(b.kind) ? b.kind : 'menu';
        const str = (v, n) => (typeof v === 'string' && v.trim() ? v.trim().slice(0, n) : null);
        const address = kind === 'server' ? str(b.address, 100) : null;
        const prev = presence.get(p.uuid);
        const joined = prev && prev.address === address && prev.at >= now() - ONLINE_MS ? prev.joined : now();
        presence.set(p.uuid, {
            kind,
            version: str(b.version, 20),
            server: kind === 'server' ? str(b.server, 60) : null,
            address,
            joined,
            at: now(),
        });
        const since = Number.isInteger(b.since) && b.since >= 0 ? b.since : null;
        let messages = [];
        if (since !== null) {
            const [rows] = await pool.query(
                'SELECT * FROM lux_messages WHERE to_uuid = ? AND id > ? ORDER BY id ASC LIMIT 50', [p.uuid, since]
            );
            messages = rows.map((m) => messageOut(m, p.uuid));
        }
        const [[reqCount]] = await pool.query('SELECT COUNT(*) AS n FROM lux_friend_requests WHERE to_uuid = ?', [p.uuid]);
        const [[unread]] = await pool.query('SELECT COUNT(*) AS n FROM lux_messages WHERE to_uuid = ? AND read = FALSE', [p.uuid]);
        const [[last]] = await pool.query('SELECT MAX(id) AS id FROM lux_messages WHERE to_uuid = ?', [p.uuid]);
        res.json({
            banned: false,
            messages,
            requests: Number(reqCount ? reqCount.n : 0),
            unread: Number(unread ? unread.n : 0),
            lastId: Number((last && last.id) || 0),
        });
    }));

    // ------------------------------------------------------------------ requests

    router.post('/friends/request', actionLimiter, wrap(async (req, res) => {
        const me = await requireSocial(req);
        const name = String((req.body && req.body.name) || '').trim();
        if (!/^[A-Za-z0-9_]{1,16}$/.test(name)) throw new HttpError(400, 'Invalid Minecraft name.');
        const [rows] = await pool.query('SELECT uuid, name FROM lux_players WHERE LOWER(name) = ? ORDER BY last_seen DESC LIMIT 1', [name.toLowerCase()]);
        const other = rows[0];
        if (!other) throw new HttpError(404, `${name} does not use Lux Client (yet).`);
        if (other.uuid === me.uuid) throw new HttpError(400, 'You cannot add yourself.');
        if (await areFriends(me.uuid, other.uuid)) throw new HttpError(409, `You are already friends with ${other.name}.`);
        if (await blocked(me.uuid, other.uuid)) throw new HttpError(409, `You blocked ${other.name} - unblock them first.`);
        if (await blocked(other.uuid, me.uuid) || await banOf(other.uuid)) {
            throw new HttpError(403, `You cannot send ${other.name} a friend request.`);
        }
        // They already asked me: that's a yes.
        const [theirs] = await pool.query('SELECT 1 AS ok FROM lux_friend_requests WHERE from_uuid = ? AND to_uuid = ?', [other.uuid, me.uuid]);
        if (theirs.length) {
            await makeFriends(me.uuid, other.uuid);
            return res.json({ success: true, friends: true, uuid: other.uuid, name: other.name });
        }
        const [[count]] = await pool.query('SELECT COUNT(*) AS n FROM lux_friend_requests WHERE from_uuid = ?', [me.uuid]);
        if (Number(count.n) >= MAX_OUTGOING) throw new HttpError(429, 'Too many open requests - wait until some are answered.');
        await pool.query(
            'INSERT INTO lux_friend_requests (from_uuid, to_uuid, created_at) VALUES (?, ?, ?) ON CONFLICT (from_uuid, to_uuid) DO NOTHING RETURNING from_uuid',
            [me.uuid, other.uuid, now()]
        );
        res.json({ success: true, friends: false, uuid: other.uuid, name: other.name });
    }));

    router.post('/friends/accept', actionLimiter, wrap(async (req, res) => {
        const me = await requireSocial(req);
        const other = target(req);
        const [rows] = await pool.query('SELECT 1 AS ok FROM lux_friend_requests WHERE from_uuid = ? AND to_uuid = ?', [other, me.uuid]);
        if (!rows.length) throw new HttpError(404, 'No such request.');
        const [[count]] = await pool.query('SELECT COUNT(*) AS n FROM lux_friends WHERE a_uuid = ? OR b_uuid = ?', [me.uuid, me.uuid]);
        if (Number(count.n) >= MAX_FRIENDS) throw new HttpError(409, `You can have at most ${MAX_FRIENDS} friends.`);
        await makeFriends(me.uuid, other);
        res.json({ success: true });
    }));

    router.post('/friends/decline', actionLimiter, wrap(async (req, res) => {
        const me = await requireMod(req);
        const other = target(req);
        await pool.query('DELETE FROM lux_friend_requests WHERE from_uuid = ? AND to_uuid = ?', [other, me.uuid]);
        res.json({ success: true });
    }));

    router.post('/friends/cancel', actionLimiter, wrap(async (req, res) => {
        const me = await requireMod(req);
        const other = target(req);
        await pool.query('DELETE FROM lux_friend_requests WHERE from_uuid = ? AND to_uuid = ?', [me.uuid, other]);
        res.json({ success: true });
    }));

    router.post('/friends/remove', actionLimiter, wrap(async (req, res) => {
        const me = await requireMod(req);
        await unfriend(me.uuid, target(req));
        res.json({ success: true });
    }));

    router.post('/friends/block', actionLimiter, wrap(async (req, res) => {
        const me = await requireMod(req);
        const other = target(req);
        if (other === me.uuid) throw new HttpError(400, 'You cannot block yourself.');
        if (!(await player(other))) throw new HttpError(404, 'Unknown player.');
        await unfriend(me.uuid, other);
        await pool.query('DELETE FROM lux_friend_requests WHERE (from_uuid = ? AND to_uuid = ?) OR (from_uuid = ? AND to_uuid = ?)', [me.uuid, other, other, me.uuid]);
        await pool.query(
            'INSERT INTO lux_blocks (uuid, blocked_uuid, created_at) VALUES (?, ?, ?) ON CONFLICT (uuid, blocked_uuid) DO NOTHING RETURNING uuid',
            [me.uuid, other, now()]
        );
        res.json({ success: true });
    }));

    router.post('/friends/unblock', actionLimiter, wrap(async (req, res) => {
        const me = await requireMod(req);
        await pool.query('DELETE FROM lux_blocks WHERE uuid = ? AND blocked_uuid = ?', [me.uuid, target(req)]);
        res.json({ success: true });
    }));

    router.post('/friends/mute', actionLimiter, wrap(async (req, res) => {
        const me = await requireMod(req);
        const other = target(req);
        if (req.body && req.body.muted === false) {
            await pool.query('DELETE FROM lux_mutes WHERE uuid = ? AND muted_uuid = ?', [me.uuid, other]);
        } else {
            await pool.query('INSERT INTO lux_mutes (uuid, muted_uuid) VALUES (?, ?) ON CONFLICT (uuid, muted_uuid) DO NOTHING RETURNING uuid', [me.uuid, other]);
        }
        res.json({ success: true });
    }));

    // ------------------------------------------------------------------ messages + invites

    async function requireChat(req) {
        const me = await requireSocial(req);
        const other = target(req);
        if (!(await areFriends(me.uuid, other))) throw new HttpError(403, 'You can only write to friends.');
        if (await blocked(other, me.uuid) || await blocked(me.uuid, other)) throw new HttpError(403, 'You cannot write to this player.');
        if (await banOf(other)) throw new HttpError(403, 'This player cannot receive messages right now.');
        return { me, other };
    }

    router.get('/friends/messages/:uuid', wrap(async (req, res) => {
        const me = await requireSocial(req);
        const other = target(req);
        if (!(await areFriends(me.uuid, other))) throw new HttpError(403, 'You can only read chats with friends.');
        const before = Number(req.query.before);
        const params = [me.uuid, other, other, me.uuid];
        let sql = 'SELECT * FROM lux_messages WHERE ((from_uuid = ? AND to_uuid = ?) OR (from_uuid = ? AND to_uuid = ?))';
        if (Number.isInteger(before) && before > 0) {
            sql += ' AND id < ?';
            params.push(before);
        }
        sql += ` ORDER BY id DESC LIMIT ${PAGE}`;
        const [rows] = await pool.query(sql, params);
        await pool.query('UPDATE lux_messages SET read = TRUE WHERE to_uuid = ? AND from_uuid = ? AND read = FALSE', [me.uuid, other]);
        res.json({ messages: rows.reverse().map((m) => messageOut(m, me.uuid)), more: rows.length === PAGE });
    }));

    router.post('/friends/messages/:uuid', messageLimiter, wrap(async (req, res) => {
        const { me, other } = await requireChat(req);
        // eslint-disable-next-line no-control-regex
        const text = String((req.body && req.body.text) || '').replace(/§./g, '').replace(/[\u0000-\u001f\u007f§]/g, ' ').trim();
        if (!text) throw new HttpError(400, 'Empty message.');
        if (text.length > MAX_TEXT) throw new HttpError(400, `At most ${MAX_TEXT} characters.`);
        const [ins] = await pool.query(
            'INSERT INTO lux_messages (from_uuid, to_uuid, kind, body, created_at) VALUES (?, ?, ?, ?, ?) RETURNING *',
            [me.uuid, other, 'text', text, now()]
        );
        res.json({ success: true, message: messageOut(ins.rows[0], me.uuid) });
    }));

    router.post('/friends/invite/:uuid', messageLimiter, wrap(async (req, res) => {
        const { me, other } = await requireChat(req);
        const p = presence.get(me.uuid);
        if (!p || p.kind !== 'server' || !p.address || p.at < now() - ONLINE_MS) {
            throw new HttpError(400, 'You can only invite while you are on a multiplayer server.');
        }
        const body = JSON.stringify({ server: p.server || p.address, address: p.address });
        const [ins] = await pool.query(
            'INSERT INTO lux_messages (from_uuid, to_uuid, kind, body, created_at) VALUES (?, ?, ?, ?, ?) RETURNING *',
            [me.uuid, other, 'invite', body, now()]
        );
        res.json({ success: true, message: messageOut(ins.rows[0], me.uuid) });
    }));

    // ------------------------------------------------------------------ admin

    router.get('/admin/social-bans', wrap(async (req, res) => {
        requireAdmin(req);
        const [rows] = await pool.query(
            'SELECT b.uuid, p.name, b.reason, b.banned_by, b.created_at FROM lux_social_bans b LEFT JOIN lux_players p ON p.uuid = b.uuid ORDER BY b.created_at DESC',
            []
        );
        res.json({ bans: rows.map((r) => ({ uuid: r.uuid, name: r.name, reason: r.reason, by: r.banned_by, at: Number(r.created_at) })) });
    }));

    router.post('/admin/players/:uuid/social-ban', wrap(async (req, res) => {
        const admin = requireAdmin(req);
        const uuid = target(req);
        const p = await player(uuid);
        if (!p) throw new HttpError(404, 'Not found.');
        const reason = String((req.body && req.body.reason) || '').trim().slice(0, 200) || null;
        await pool.query(
            `INSERT INTO lux_social_bans (uuid, reason, banned_by, created_at) VALUES (?, ?, ?, ?)
             ON CONFLICT (uuid) DO UPDATE SET reason = EXCLUDED.reason, banned_by = EXCLUDED.banned_by, created_at = EXCLUDED.created_at RETURNING uuid`,
            [uuid, reason, admin.username || String(admin.id), now()]
        );
        banCache.delete(uuid);
        await audit(admin, 'lux_social.ban', 'lux_player', p.name, reason);
        res.json({ success: true });
    }));

    router.delete('/admin/players/:uuid/social-ban', wrap(async (req, res) => {
        const admin = requireAdmin(req);
        const uuid = target(req);
        await pool.query('DELETE FROM lux_social_bans WHERE uuid = ?', [uuid]);
        banCache.delete(uuid);
        const p = await player(uuid);
        await audit(admin, 'lux_social.unban', 'lux_player', p ? p.name : uuid, null);
        res.json({ success: true });
    }));

    const cleanup = setInterval(async () => {
        const t = now();
        for (const [k, v] of presence) if (v.at < t - 10 * 60 * 1000) presence.delete(k);
        for (const [k, v] of banCache) if (v.until < t) banCache.delete(k);
        try {
            await pool.query('DELETE FROM lux_messages WHERE created_at < ?', [t - KEEP_MESSAGES_MS]);
        } catch {
            // next round
        }
    }, 10 * 60 * 1000);
    cleanup.unref();

    return {
        /** For the admin player panel. */
        async socialBan(uuid) {
            return banOf(uuid);
        },
    };
}

module.exports = { createFriendTables, attachFriends };
