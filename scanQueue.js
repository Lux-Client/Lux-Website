// Warteschlange der Virenpruefung fuer eigene Dateien in Modpack-Codes.
//
// Jede hochgeladene Datei bekommt einen Auftrag in code_scan_jobs. Ein einziger Arbeiter
// nimmt sich immer genau einen Auftrag nach dem anderen und laesst ihn von ClamAV pruefen
// (clamavEngine.js startet clamd dafuer erst bei Bedarf und stoppt ihn im Leerlauf).
//
// Die Warteschlange liegt in der Datenbank, nicht im Speicher: Stuerzt der Server oder
// clamd ab, bleibt sie erhalten. Ein Auftrag, der gerade lief, wird beim naechsten Start
// (oder wenn clamd mitten im Scan wegbricht) einfach noch einmal gemacht.
//
// Solange eine Datei nicht als sauber gilt, funktioniert ein Code mit ihr nicht (siehe
// codeGate in codes_system.js). Im Admin-Panel kann die Pruefung pausiert werden
// (Wartung); dann bleiben neue Dateien in der Warteschlange, bis es weitergeht.
const crypto = require('crypto');
const fs = require('fs');
const fsp = require('fs/promises');
const os = require('os');
const path = require('path');

const engine = require('./clamavEngine');
const { builtinScan, virusTotalLookup } = require('./codeFileScan');

const MAX_ATTEMPTS = Number(process.env.LUX_SCAN_MAX_ATTEMPTS || 5);
const TICK_MS = Number(process.env.LUX_SCAN_TICK_SECONDS || 30) * 1000;
const RESCAN_AFTER_HOURS = Number(process.env.LUX_CODE_FILE_RESCAN_HOURS || 24);
const RESCAN_BATCH = Number(process.env.LUX_CODE_FILE_RESCAN_BATCH || 200);

let pool = null;
let schemaReady = null;
let started = false;
let tickTimer = null;
let retryTimer = null;
let looping = false;
let loopAgain = false;
let idleWaiters = [];

const worker = {
    status: 'stopped', // stopped | idle | working | waiting_engine | paused
    current: null,
    lastJobAt: null,
    nextRetryAt: null,
    processed: 0,
    startedAt: null
};

const events = [];
function log(type, message, extra = {}) {
    events.unshift({ at: Date.now(), type, message, ...extra });
    if (events.length > 150) events.length = 150;
    if (type === 'error' || type === 'warning') console.warn(`[ScanQueue] ${message}`);
    else console.log(`[ScanQueue] ${message}`);
}

engine.onChange((snap) => {
    const last = events[0];
    const message = `ClamAV ${snap.status}`;
    if (!last || last.type !== 'engine' || last.message !== message) {
        log('engine', message, snap.status === 'error' && snap.lastError ? { detail: snap.lastError } : {});
    }
});

function usePool(value) {
    if (value && value !== pool) {
        pool = value;
        schemaReady = null;
    }
    return pool;
}

function ensureSchema() {
    if (!pool) return Promise.resolve();
    if (!schemaReady) {
        schemaReady = (async () => {
            await pool.query(`
                CREATE TABLE IF NOT EXISTS code_scan_jobs (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    sha256 CHAR(64) NOT NULL,
                    reason VARCHAR(16) NOT NULL,
                    status VARCHAR(16) NOT NULL,
                    attempts INTEGER NOT NULL DEFAULT 0,
                    restarts INTEGER NOT NULL DEFAULT 0,
                    result VARCHAR(16),
                    engine VARCHAR(64),
                    detail VARCHAR(500),
                    requested_by VARCHAR(100),
                    next_attempt_at TIMESTAMPTZ,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                    started_at TIMESTAMPTZ,
                    finished_at TIMESTAMPTZ
                )
            `);
            await pool.query('CREATE INDEX IF NOT EXISTS idx_code_scan_jobs_status ON code_scan_jobs(status, id)');
            await pool.query('CREATE INDEX IF NOT EXISTS idx_code_scan_jobs_hash ON code_scan_jobs(sha256)');
            await pool.query(`
                CREATE TABLE IF NOT EXISTS code_scan_state (
                    id INTEGER PRIMARY KEY,
                    paused BOOLEAN NOT NULL DEFAULT FALSE,
                    pause_reason VARCHAR(255),
                    paused_by VARCHAR(100),
                    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
                )
            `);
            await pool.query('INSERT INTO code_scan_state (id, paused) VALUES (1, FALSE) ON CONFLICT (id) DO NOTHING RETURNING id');
        })().catch((err) => {
            schemaReady = null;
            throw err;
        });
    }
    return schemaReady;
}

async function readState() {
    await ensureSchema();
    const [rows] = await pool.query('SELECT paused, pause_reason, paused_by, updated_at FROM code_scan_state WHERE id = 1');
    const row = rows[0] || {};
    return {
        paused: Boolean(row.paused),
        reason: row.pause_reason || null,
        by: row.paused_by || null,
        since: row.updated_at || null
    };
}

function trimHash(value) {
    return String(value || '').trim().toLowerCase();
}

// Neuer Auftrag. Steht fuer die Datei schon einer an, wird kein zweiter angelegt.
async function enqueue(hash, reason = 'upload', { by = null, executor = null } = {}) {
    const db = executor || pool;
    if (!db) return null;
    await ensureSchema();
    const sha = trimHash(hash);
    const [open] = await db.query(
        `SELECT id FROM code_scan_jobs WHERE sha256 = ? AND status IN ('queued', 'running') LIMIT 1`,
        [sha]
    );
    if (open[0]) return open[0].id;
    const [rows] = await db.query(
        `INSERT INTO code_scan_jobs (sha256, reason, status, requested_by) VALUES (?, ?, 'queued', ?) RETURNING id`,
        [sha, reason, by]
    );
    if (!executor) kick();
    return rows[0] ? rows[0].id : null;
}

async function setBlobStatus(hash, status, engineName, reason) {
    await pool.query(
        `UPDATE modpack_code_blobs SET scan_status = ?, scan_engine = ?, scan_reason = ?, scanned_at = NOW()
          WHERE sha256 = ?`,
        [status, engineName || null, reason ? String(reason).slice(0, 250) : null, hash]
    );
}

async function blobStatus(hash) {
    const [rows] = await pool.query('SELECT scan_status FROM modpack_code_blobs WHERE sha256 = ?', [hash]);
    if (rows.length === 0) return null;
    const statuses = rows.map((row) => row.scan_status);
    if (statuses.includes('infected')) return 'infected';
    if (statuses.every((s) => s === 'clean')) return 'clean';
    return statuses.find((s) => s && s !== 'clean') || 'pending';
}

function backoffMs(attempt) {
    return Math.min(30 * 60 * 1000, 15000 * Math.pow(2, Math.max(0, attempt - 1)));
}

async function copyToTemp(hash) {
    const { getStorage } = require('./storage');
    const { codeFileKey } = require('./codeFiles');
    const stored = await getStorage().get(codeFileKey(hash));
    const temp = path.join(os.tmpdir(), `lux-scan-${hash}-${crypto.randomBytes(4).toString('hex')}`);
    await new Promise((resolve, reject) => {
        const out = fs.createWriteStream(temp);
        stored.stream.on('error', reject);
        out.on('error', reject);
        out.on('finish', resolve);
        stored.stream.pipe(out);
    });
    return temp;
}

async function finishJob(job, fields) {
    await pool.query(
        `UPDATE code_scan_jobs SET status = ?, result = ?, engine = ?, detail = ?, attempts = ?, finished_at = NOW(), next_attempt_at = NULL
          WHERE id = ?`,
        [fields.status, fields.result || null, fields.engine || null, fields.detail ? String(fields.detail).slice(0, 490) : null, fields.attempts, job.id]
    );
}

async function requeue(job, { attempts, detail, delayMs }) {
    const seconds = Math.max(1, Math.round(delayMs / 1000));
    await pool.query(
        `UPDATE code_scan_jobs SET status = 'queued', attempts = ?, detail = ?, started_at = NULL,
                next_attempt_at = NOW() + INTERVAL '${seconds} seconds'
          WHERE id = ?`,
        [attempts, detail ? String(detail).slice(0, 490) : null, job.id]
    );
}

// Einen Auftrag abarbeiten. Liefert 'next' (weiter), oder 'wait' (Engine fehlt, spaeter).
async function processJob(job) {
    const hash = trimHash(job.sha256);
    const current = await blobStatus(hash);
    if (current === null) {
        await finishJob(job, { status: 'cancelled', detail: 'File was deleted before the check', attempts: job.attempts });
        log('job', `#${job.id} skipped, file no longer stored`, { jobId: job.id });
        return 'next';
    }

    let temp = null;
    try {
        try {
            temp = await copyToTemp(hash);
        } catch (err) {
            await finishJob(job, { status: 'cancelled', detail: `File is no longer stored (${err.code || err.message})`, attempts: job.attempts });
            log('warning', `#${job.id} cancelled, stored file missing`, { jobId: job.id });
            return 'next';
        }

        // Ohne ClamAV gibt es nichts zu warten: die eigene Pruefung reicht (Entwicklung).
        if (engine.mode() !== 'off') {
            try {
                await engine.ensureReady();
            } catch (err) {
                // Kein Fehlversuch: die Datei kann nichts dafuer. Spaeter nochmal.
                const delay = backoffMs(Math.min(6, (job.restarts || 0) + 1));
                await pool.query('UPDATE code_scan_jobs SET restarts = restarts + 1 WHERE id = ?', [job.id]);
                await requeue(job, { attempts: job.attempts, detail: `Waiting for ClamAV: ${err.message}`, delayMs: delay });
                worker.nextRetryAt = Date.now() + delay;
                log('warning', `ClamAV not ready (${err.message}), retrying in ${Math.round(delay / 1000)}s`);
                return 'wait';
            }
        }

        const attempts = job.attempts + 1;
        const engines = [];
        let verdict = await builtinScan(temp);
        if (verdict.status === 'clean') {
            engines.push('lux');
            if (engine.mode() !== 'off') {
                verdict = await engine.scan(temp);
                if (verdict.status === 'clean') engines.push('clamav');
            }
        }
        if (verdict.status === 'clean') {
            const vt = await virusTotalLookup(hash).catch(() => null);
            if (vt && vt.status === 'infected') verdict = vt;
            else if (vt && vt.status === 'clean') engines.push('virustotal');
        }

        if (verdict.status === 'error') {
            if (attempts >= MAX_ATTEMPTS) {
                await finishJob(job, { status: 'failed', result: 'error', engine: verdict.engine, detail: verdict.reason, attempts });
                // Neue Datei: bleibt gesperrt, bis ein Admin sie erneut pruefen laesst.
                // Nachpruefung: der alte saubere Befund bleibt stehen.
                if (job.reason !== 'rescan') await setBlobStatus(hash, 'error', verdict.engine, verdict.reason);
                log('error', `#${job.id} failed after ${attempts} attempts: ${verdict.reason}`, { jobId: job.id });
            } else {
                const delay = backoffMs(attempts);
                await requeue(job, { attempts, detail: verdict.reason, delayMs: delay });
                worker.nextRetryAt = Date.now() + delay;
                log('warning', `#${job.id} scan error (${verdict.reason}), attempt ${attempts}/${MAX_ATTEMPTS}, again in ${Math.round(delay / 1000)}s`, { jobId: job.id });
            }
            return 'next';
        }

        if (verdict.status === 'infected') {
            await setBlobStatus(hash, 'infected', verdict.engine, verdict.reason);
            await finishJob(job, { status: 'done', result: 'infected', engine: verdict.engine, detail: verdict.reason, attempts });
            log('infected', `#${job.id} ${hash.slice(0, 12)} blocked: ${verdict.reason}`, { jobId: job.id, sha256: hash });
        } else {
            const used = engines.join('+');
            await setBlobStatus(hash, 'clean', used, null);
            await finishJob(job, { status: 'done', result: 'clean', engine: used, attempts });
            log('job', `#${job.id} ${hash.slice(0, 12)} clean (${used})`, { jobId: job.id });
        }
        worker.processed += 1;
        worker.lastJobAt = Date.now();
        return 'next';
    } finally {
        if (temp) await fsp.rm(temp, { force: true }).catch(() => {});
    }
}

async function claimNext() {
    const [rows] = await pool.query(
        `SELECT id, sha256, reason, attempts, restarts FROM code_scan_jobs
          WHERE status = 'queued' AND (next_attempt_at IS NULL OR next_attempt_at <= NOW())
          ORDER BY CASE WHEN reason = 'rescan' THEN 1 ELSE 0 END, id
          LIMIT 1`
    );
    const job = rows[0];
    if (!job) return null;
    const [claimed] = await pool.query(
        `UPDATE code_scan_jobs SET status = 'running', started_at = NOW() WHERE id = ? AND status = 'queued' RETURNING id`,
        [job.id]
    );
    if (claimed.length === 0) return null;
    return { ...job, attempts: Number(job.attempts) || 0, restarts: Number(job.restarts) || 0 };
}

async function nextDueIn() {
    const [rows] = await pool.query(
        `SELECT MIN(next_attempt_at) AS due FROM code_scan_jobs WHERE status = 'queued'`
    );
    const due = rows[0] && rows[0].due ? new Date(rows[0].due).getTime() : null;
    return due ? Math.max(1000, due - Date.now()) : null;
}

function scheduleRetry(ms) {
    if (retryTimer) clearTimeout(retryTimer);
    worker.nextRetryAt = Date.now() + ms;
    retryTimer = setTimeout(() => { retryTimer = null; kick(); }, ms);
    if (retryTimer.unref) retryTimer.unref();
}

async function loop() {
    if (!pool || !started) return;
    if (looping) {
        loopAgain = true;
        return;
    }
    looping = true;
    try {
        await ensureSchema();
        for (;;) {
            const state = await readState();
            if (state.paused) {
                if (worker.status !== 'paused') log('state', `Paused${state.reason ? `: ${state.reason}` : ''}`);
                worker.status = 'paused';
                worker.current = null;
                await engine.stop().catch(() => {});
                break;
            }
            const job = await claimNext();
            if (!job) {
                const due = await nextDueIn();
                worker.current = null;
                if (due) {
                    worker.status = 'waiting_engine';
                    scheduleRetry(due);
                } else {
                    if (worker.status === 'working') log('state', 'Queue empty, going idle');
                    worker.status = 'idle';
                    worker.nextRetryAt = null;
                    engine.scheduleIdleStop();
                }
                break;
            }
            worker.status = 'working';
            worker.nextRetryAt = null;
            worker.current = { id: job.id, sha256: trimHash(job.sha256), reason: job.reason, attempt: job.attempts + 1, startedAt: Date.now() };
            log('job', `#${job.id} started (${job.reason}, attempt ${job.attempts + 1})`, { jobId: job.id });
            let outcome;
            try {
                outcome = await processJob(job);
            } catch (err) {
                // Unerwartet (z.B. Datenbank weg): Auftrag zurueck, spaeter weiter.
                log('error', `#${job.id} crashed: ${err.message}`, { jobId: job.id });
                await requeue(job, { attempts: job.attempts, detail: err.message, delayMs: 15000 }).catch(() => {});
                outcome = 'wait';
            }
            worker.current = null;
            if (outcome === 'wait') {
                worker.status = 'waiting_engine';
                const due = await nextDueIn().catch(() => 15000);
                scheduleRetry(due || 15000);
                break;
            }
        }
    } catch (err) {
        log('error', `Worker loop error: ${err.message}`);
        scheduleRetry(15000);
    } finally {
        looping = false;
        if (loopAgain) {
            loopAgain = false;
            setImmediate(() => loop());
        } else if (worker.status !== 'working') {
            const waiters = idleWaiters;
            idleWaiters = [];
            waiters.forEach((resolve) => resolve());
        }
    }
}

function kick() {
    if (!started) return;
    setImmediate(() => loop());
}

// Beim Start: was lief, als der Server ausging, wird neu gemacht.
async function start(dbPool) {
    usePool(dbPool);
    if (!pool) return;
    await ensureSchema();
    const [rows] = await pool.query(
        `UPDATE code_scan_jobs SET status = 'queued', restarts = restarts + 1, started_at = NULL,
                detail = 'Interrupted (server restart), checking again'
          WHERE status = 'running' RETURNING id`
    );
    if (rows.length > 0) log('warning', `Recovered ${rows.length} interrupted job(s), they run again`);
    // Dateien ohne Auftrag und ohne Befund (z.B. vor diesem System hochgeladen) einreihen.
    const [missing] = await pool.query(
        `SELECT DISTINCT b.sha256 FROM modpack_code_blobs b
           LEFT JOIN code_scan_jobs j ON j.sha256 = b.sha256 AND j.status IN ('queued', 'running')
          WHERE (b.scan_status IS NULL OR b.scan_status = 'pending') AND j.id IS NULL`
    );
    for (const row of missing) await enqueue(row.sha256, 'upload', { by: 'recovery' });
    if (!started) {
        started = true;
        worker.startedAt = Date.now();
        worker.status = 'idle';
        log('state', `Worker started (ClamAV mode: ${engine.mode()})`);
        tickTimer = setInterval(() => kick(), TICK_MS);
        if (tickTimer.unref) tickTimer.unref();
    }
    kick();
}

async function shutdown() {
    started = false;
    if (tickTimer) clearInterval(tickTimer);
    if (retryTimer) clearTimeout(retryTimer);
    tickTimer = null;
    retryTimer = null;
    worker.status = 'stopped';
    await engine.stop().catch(() => {});
}

// Fuer Tests: wartet, bis der Arbeiter nichts mehr zu tun hat.
function waitIdle(timeoutMs = 20000) {
    return new Promise((resolve, reject) => {
        const timer = setTimeout(() => reject(new Error('scan queue did not become idle')), timeoutMs);
        const check = () => {
            if (!looping && worker.status !== 'working') {
                clearTimeout(timer);
                resolve();
            } else {
                idleWaiters.push(check);
            }
        };
        setImmediate(check);
    });
}

async function setPaused(paused, { reason = null, by = null } = {}) {
    await ensureSchema();
    await pool.query(
        'UPDATE code_scan_state SET paused = ?, pause_reason = ?, paused_by = ?, updated_at = NOW() WHERE id = 1',
        [Boolean(paused), paused ? (reason ? String(reason).slice(0, 250) : null) : null, by]
    );
    log('state', paused ? `Maintenance started${by ? ` by ${by}` : ''}${reason ? `: ${reason}` : ''}` : `Maintenance ended${by ? ` by ${by}` : ''}`);
    kick();
    return readState();
}

async function retryJob(id, by = null) {
    await ensureSchema();
    const [rows] = await pool.query('SELECT id, sha256, status FROM code_scan_jobs WHERE id = ?', [id]);
    const job = rows[0];
    if (!job) return null;
    if (job.status === 'queued') {
        await pool.query('UPDATE code_scan_jobs SET next_attempt_at = NULL WHERE id = ?', [id]);
        kick();
        return id;
    }
    if (job.status === 'running') return id;
    const hash = trimHash(job.sha256);
    if ((await blobStatus(hash)) === 'error') {
        await pool.query(`UPDATE modpack_code_blobs SET scan_status = 'pending' WHERE sha256 = ?`, [hash]);
    }
    return enqueue(hash, 'manual', { by });
}

async function cancelJob(id) {
    await ensureSchema();
    const [rows] = await pool.query(
        `UPDATE code_scan_jobs SET status = 'cancelled', finished_at = NOW(), detail = 'Cancelled by an admin'
          WHERE id = ? AND status = 'queued' RETURNING id, sha256`,
        [id]
    );
    if (rows.length === 0) return false;
    log('job', `#${id} cancelled by an admin`, { jobId: id });
    return true;
}

async function rescanFile(hash, by = null) {
    const sha = trimHash(hash);
    if ((await blobStatus(sha)) === null) return null;
    return enqueue(sha, 'manual', { by });
}

// Admin-Entscheidung, z.B. Fehlalarm freigeben oder eine Datei von Hand sperren.
async function setVerdict(hash, status, by = null) {
    const sha = trimHash(hash);
    if (!['clean', 'infected'].includes(status)) throw new Error('status must be clean or infected');
    if ((await blobStatus(sha)) === null) return false;
    await setBlobStatus(sha, status, 'admin', by ? `Set by ${by}` : 'Set by an admin');
    await pool.query(
        `UPDATE code_scan_jobs SET status = 'cancelled', finished_at = NOW(), detail = 'Decided by an admin'
          WHERE sha256 = ? AND status = 'queued'`,
        [sha]
    );
    log('state', `${sha.slice(0, 12)} marked ${status}${by ? ` by ${by}` : ''}`);
    return true;
}

// Gespeicherte Dateien regelmaessig neu pruefen lassen (Signaturen werden besser).
async function enqueueRescans({ limit = RESCAN_BATCH } = {}) {
    await ensureSchema();
    const [rows] = await pool.query(
        `SELECT DISTINCT b.sha256 FROM modpack_code_blobs b
           LEFT JOIN code_scan_jobs j ON j.sha256 = b.sha256 AND j.status IN ('queued', 'running')
          WHERE b.scan_status = 'clean'
            AND (b.scanned_at IS NULL OR b.scanned_at < NOW() - INTERVAL '${RESCAN_AFTER_HOURS} hours')
            AND j.id IS NULL
          LIMIT ${Math.max(1, Math.floor(limit))}`
    );
    for (const row of rows) await enqueue(row.sha256, 'rescan', { by: 'schedule' });
    return rows.length;
}

// Position in der Warteschlange fuer die Fehlermeldung beim Import.
async function queueInfo(hashes) {
    await ensureSchema();
    const wanted = hashes.map(trimHash);
    if (wanted.length === 0) return { position: null, queued: 0 };
    const [rows] = await pool.query(
        `SELECT id, sha256 FROM code_scan_jobs WHERE status IN ('queued', 'running') ORDER BY CASE WHEN reason = 'rescan' THEN 1 ELSE 0 END, id`
    );
    let position = null;
    rows.forEach((row, index) => {
        if (position === null && wanted.includes(trimHash(row.sha256))) position = index + 1;
    });
    return { position, queued: rows.length };
}

async function overview({ limit = 50 } = {}) {
    await ensureSchema();
    const state = await readState();
    const [counts] = await pool.query('SELECT status, COUNT(*) AS n FROM code_scan_jobs GROUP BY status');
    const [queue] = await pool.query(
        `SELECT j.id, j.sha256, j.reason, j.status, j.attempts, j.restarts, j.detail, j.requested_by,
                j.next_attempt_at, j.created_at, j.started_at
           FROM code_scan_jobs j
          WHERE j.status IN ('queued', 'running')
          ORDER BY CASE WHEN j.status = 'running' THEN 0 ELSE 1 END, CASE WHEN j.reason = 'rescan' THEN 1 ELSE 0 END, j.id
          LIMIT ${Math.max(1, Math.floor(limit))}`
    );
    const [recent] = await pool.query(
        `SELECT id, sha256, reason, status, result, engine, detail, attempts, restarts, requested_by, created_at, started_at, finished_at
           FROM code_scan_jobs WHERE status IN ('done', 'failed', 'cancelled')
          ORDER BY finished_at DESC, id DESC LIMIT ${Math.max(1, Math.floor(limit))}`
    );
    const [blobs] = await pool.query(
        `SELECT scan_status, COUNT(DISTINCT sha256) AS n FROM modpack_code_blobs GROUP BY scan_status`
    );
    const hashes = [...new Set([...queue, ...recent].map((row) => trimHash(row.sha256)))];
    const names = await fileNames(hashes);
    const describe = (row) => ({
        id: row.id,
        sha256: trimHash(row.sha256),
        fileName: names.get(trimHash(row.sha256)) || null,
        reason: row.reason,
        status: row.status,
        result: row.result || null,
        engine: row.engine || null,
        detail: row.detail || null,
        attempts: Number(row.attempts) || 0,
        restarts: Number(row.restarts) || 0,
        requestedBy: row.requested_by || null,
        nextAttemptAt: row.next_attempt_at || null,
        createdAt: row.created_at || null,
        startedAt: row.started_at || null,
        finishedAt: row.finished_at || null
    });
    const countMap = Object.fromEntries(counts.map((row) => [row.status, Number(row.n)]));
    const fileMap = Object.fromEntries(blobs.map((row) => [row.scan_status || 'pending', Number(row.n)]));
    return {
        state,
        worker: { ...worker, maxAttempts: MAX_ATTEMPTS },
        engine: engine.snapshot(),
        counts: {
            queued: countMap.queued || 0,
            running: countMap.running || 0,
            done: countMap.done || 0,
            failed: countMap.failed || 0,
            cancelled: countMap.cancelled || 0
        },
        files: fileMap,
        queue: queue.map(describe),
        recent: recent.map(describe),
        events: events.slice(0, 60)
    };
}

async function fileNames(hashes) {
    const names = new Map();
    if (hashes.length === 0) return names;
    const [rows] = await pool.query(
        `SELECT sha256, file_name FROM modpack_code_files WHERE sha256 IN (${hashes.map(() => '?').join(', ')})`,
        hashes
    );
    for (const row of rows) {
        const sha = trimHash(row.sha256);
        if (!names.has(sha)) names.set(sha, row.file_name);
    }
    return names;
}

async function pruneHistory(days = 14) {
    await ensureSchema();
    await pool.query(
        `DELETE FROM code_scan_jobs WHERE status IN ('done', 'cancelled', 'failed')
            AND finished_at < NOW() - INTERVAL '${Math.max(1, Math.floor(days))} days'`
    );
}

async function engineAction(action) {
    if (action === 'start') {
        await engine.ensureReady();
        engine.scheduleIdleStop();
    } else if (action === 'stop') {
        await engine.stop();
    } else if (action === 'update') {
        await engine.updateSignatures({ force: true });
    } else {
        throw new Error('Unknown action');
    }
    log('state', `Admin: ClamAV ${action}`);
    return engine.snapshot();
}

