/* Email + password accounts: registration, confirmation, login, 2FA, recovery codes,
   password reset, lockout and the Resend quota switch-off.
   Run with: node tests/accountAuth.test.js */

const assert = require('assert');
const http = require('http');
const path = require('path');
const Module = require('module');

process.env.NODE_ENV = 'test';
process.env.GOOGLE_CLIENT_ID = 'test-client';
process.env.GOOGLE_CLIENT_SECRET = 'test-secret';
process.env.SESSION_SECRET = 'test-session-secret';
delete process.env.RESEND_API_KEY;

const { newDb } = require('pg-mem');
const db = newDb({ autoCreateForeignKeyIndices: true });
db.public.registerFunction({ name: 'version', returns: 'text', implementation: () => 'PostgreSQL 14 (pg-mem)' });
const pgAdapter = db.adapters.createPg();
const originalLoad = Module._load;
Module._load = function (request, parent, isMain) {
    if (request === 'pg') return pgAdapter;
    if (request === 'dotenv') return { config: () => ({}) };
    return originalLoad.call(this, request, parent, isMain);
};

const SITE = path.resolve(__dirname, '..');
const pool = require(path.join(SITE, 'database.js'));
const email = require(path.join(SITE, 'email.js'));
const c = require(path.join(SITE, 'auth', 'crypto.js'));

const outbox = [];
let nextResult = null;
email._setTransport(async (msg) => {
    if (nextResult) { const r = nextResult; nextResult = null; return r; }
    outbox.push(msg);
    return { ok: true, id: `test-${outbox.length}` };
});

let clock = Date.parse('2026-11-16T10:00:00Z');
email._setClock(() => new Date(clock));

function tokenFrom(msg, param = 'token') {
    const m = String(msg.text).match(new RegExp(`${param}=([A-Za-z0-9_-]+)`));
    return m && decodeURIComponent(m[1]);
}

class Client {
    constructor(port) { this.port = port; this.cookie = ''; }
    request(method, url, body) {
        return new Promise((resolve, reject) => {
            const payload = body === undefined ? null : JSON.stringify(body);
            const req = http.request({
                host: '127.0.0.1', port: this.port, method, path: url,
                headers: {
                    ...(payload ? { 'Content-Type': 'application/json', 'Content-Length': Buffer.byteLength(payload) } : {}),
                    ...(this.cookie ? { Cookie: this.cookie } : {}),
                },
            }, (res) => {
                const set = res.headers['set-cookie'];
                if (set) this.cookie = set.map((s) => s.split(';')[0]).join('; ');
                const chunks = [];
                res.on('data', (d) => chunks.push(d));
                res.on('end', () => {
                    const text = Buffer.concat(chunks).toString('utf8');
                    let parsed = text;
                    try { parsed = JSON.parse(text); } catch { /* keep text */ }
                    resolve({ status: res.statusCode, body: parsed });
                });
            });
            req.on('error', reject);
            if (payload) req.write(payload);
            req.end();
        });
    }
    get(url) { return this.request('GET', url); }
    post(url, body = {}) { return this.request('POST', url, body); }
}

async function main() {
    const conn = await pool.getConnection();
    await conn.query(`
        CREATE TABLE users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            google_id VARCHAR(255) UNIQUE,
            username VARCHAR(50) UNIQUE NOT NULL,
            email VARCHAR(100),
            avatar VARCHAR(1000),
            bio TEXT,
            role VARCHAR(20) NOT NULL DEFAULT 'user',
            last_login TIMESTAMPTZ,
            banned BOOLEAN NOT NULL DEFAULT FALSE,
            ban_reason TEXT,
            ban_expires TIMESTAMPTZ,
            is_private BOOLEAN NOT NULL DEFAULT FALSE,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
    `);
    // An old Google account, to check the migration and the shared-email case.
    await conn.query("INSERT INTO users (google_id, username, email) VALUES ('g-1', 'googler', 'googler@example.com')");
    await require(path.join(SITE, 'db_init_auth.js')).createAuthTables(conn);
    conn.release();

    const express = require('express');
    const session = require('express-session');
    const passport = require(path.join(SITE, 'passport-setup.js'));
    const app = express();
    app.use(session({ secret: 'x', resave: false, saveUninitialized: false }));
    app.use(passport.initialize());
    app.use(passport.session());
    app.use(require(path.join(SITE, 'routes', 'accountAuth.js'))({ pool, email, now: () => clock, limitScale: 10 }));
    app.get('/api/user', (req, res) => res.json(req.isAuthenticated() ? { loggedIn: true, user: req.user } : { loggedIn: false }));
    app.get('/auth/logout', (req, res) => req.logout(() => res.json({ ok: true })));
    const server = app.listen(0);
    await new Promise((r) => server.once('listening', r));
    const port = server.address().port;
    const client = () => new Client(port);

    let failures = 0;
    const test = async (name, fn) => {
        try { await fn(); console.log(`  ok   ${name}`); }
        catch (err) { failures++; console.error(`  FAIL ${name}\n       ${err.stack}`); }
    };

    const alice = client();
    const PW = 'correct horse battery';

    await test('crypto: password hash round trip, TOTP matches RFC 6238 test vector', async () => {
        const hash = await c.hashPassword('hunter22hunter');
        assert.ok(await c.verifyPassword('hunter22hunter', hash));
        assert.ok(!(await c.verifyPassword('hunter22hunteR', hash)));
        // RFC 6238 SHA1 secret "12345678901234567890" at T=59s -> 94287082 (last 6 digits 287082)
        const secret = c.base32Encode(Buffer.from('12345678901234567890'));
        assert.strictEqual(c.totpAt(secret, 59 * 1000), '287082');
        assert.strictEqual(c.decrypt(c.encrypt('abc')), 'abc');
    });

    await test('migration: Google accounts count as verified, google_id is optional', async () => {
        const [rows] = await pool.query('SELECT email_verified FROM users WHERE google_id = ?', ['g-1']);
        assert.strictEqual(rows[0].email_verified, true);
    });

    await test('config: registration open while emails can be sent', async () => {
        const r = await alice.get('/api/auth/config');
        assert.strictEqual(r.status, 200);
        assert.strictEqual(r.body.registrationOpen, true);
        assert.strictEqual(r.body.google, true);
    });

    await test('register: validates input, sends confirmation, blocks login until confirmed', async () => {
        let r = await alice.post('/api/auth/register', { username: 'a', email: 'alice@example.com', password: PW });
        assert.strictEqual(r.status, 400);
        r = await alice.post('/api/auth/register', { username: 'alice', email: 'alice@example.com', password: 'short' });
        assert.strictEqual(r.body.field, 'password');
        r = await alice.post('/api/auth/register', { username: 'alice', email: 'Alice@Example.com', password: PW });
        assert.strictEqual(r.status, 200, JSON.stringify(r.body));
        assert.strictEqual(outbox.length, 1);
        assert.strictEqual(outbox[0].to, 'alice@example.com');
        r = await alice.post('/api/auth/login', { email: 'alice@example.com', password: PW });
        assert.strictEqual(r.status, 403);
        assert.strictEqual(r.body.code, 'email_unverified');
    });

    await test('register: taken username refused, existing email gets a notice instead of a second account', async () => {
        const bob = client();
        let r = await bob.post('/api/auth/register', { username: 'ALICE', email: 'bob@example.com', password: PW });
        assert.strictEqual(r.status, 409);
        const before = outbox.length;
        r = await bob.post('/api/auth/register', { username: 'googler2', email: 'googler@example.com', password: PW });
        assert.strictEqual(r.status, 200);
        assert.strictEqual(outbox.length, before + 1);
        assert.match(outbox[outbox.length - 1].subject, /already have/);
        const [rows] = await pool.query('SELECT id FROM users WHERE LOWER(email) = ?', ['googler@example.com']);
        assert.strictEqual(rows.length, 1);
    });

    await test('verify-email: link logs in once, no secrets in /api/user', async () => {
        const token = tokenFrom(outbox[0]);
        let r = await alice.post('/api/auth/verify-email', { token });
        assert.strictEqual(r.status, 200, JSON.stringify(r.body));
        r = await alice.get('/api/user');
        assert.strictEqual(r.body.loggedIn, true);
        assert.strictEqual(r.body.user.username, 'alice');
        assert.strictEqual(r.body.user.password_hash, undefined);
        assert.strictEqual(r.body.user.totp_secret, undefined);
        assert.strictEqual(r.body.user.has_password, true);
        r = await client().post('/api/auth/verify-email', { token });
        assert.strictEqual(r.status, 400);
    });

    await test('login: wrong password refused, right one works', async () => {
        await alice.get('/auth/logout');
        let r = await alice.post('/api/auth/login', { email: 'alice@example.com', password: 'nope nope nope' });
        assert.strictEqual(r.status, 401);
        r = await alice.post('/api/auth/login', { email: 'nobody@example.com', password: PW });
        assert.strictEqual(r.status, 401);
        r = await alice.post('/api/auth/login', { email: 'ALICE@example.com', password: PW, returnTo: '//evil.com' });
        assert.strictEqual(r.status, 200);
        assert.strictEqual(r.body.returnTo, '/dashboard');
    });

    let secret;
    let recovery;
    await test('2FA: setup needs a valid code, gives recovery codes', async () => {
        let r = await alice.post('/api/account/totp/setup');
        assert.strictEqual(r.status, 200);
        assert.ok(r.body.qr.startsWith('data:image/png'));
        secret = r.body.secret;
        r = await alice.post('/api/account/totp/enable', { code: '000000' });
        assert.strictEqual(r.status, 400);
        r = await alice.post('/api/account/totp/enable', { code: c.totpAt(secret, clock) });
        assert.strictEqual(r.status, 200);
        assert.strictEqual(r.body.recoveryCodes.length, 10);
        recovery = r.body.recoveryCodes;
        r = await alice.get('/api/account/security');
        assert.strictEqual(r.body.totpEnabled, true);
        assert.strictEqual(r.body.recoveryCodesLeft, 10);
    });

    await test('2FA: password alone is not enough, codes are single use', async () => {
        await alice.get('/auth/logout');
        clock += 60 * 1000;
        let r = await alice.post('/api/auth/login', { email: 'alice@example.com', password: PW });
        assert.strictEqual(r.body.twoFactor, true);
        assert.deepStrictEqual(r.body.methods, ['totp', 'recovery']);
        r = await alice.get('/api/user');
        assert.strictEqual(r.body.loggedIn, false);
        r = await alice.post('/api/auth/login/2fa', { code: '123456' });
        assert.strictEqual(r.status, 401);
        const code = c.totpAt(secret, clock);
        r = await alice.post('/api/auth/login/2fa', { code });
        assert.strictEqual(r.status, 200);
        assert.strictEqual((await alice.get('/api/user')).body.loggedIn, true);

        await alice.get('/auth/logout');
        await alice.post('/api/auth/login', { email: 'alice@example.com', password: PW });
        r = await alice.post('/api/auth/login/2fa', { code });
        assert.strictEqual(r.status, 401, 'same code twice');
        r = await alice.post('/api/auth/login/2fa', { recoveryCode: recovery[0].toUpperCase() });
        assert.strictEqual(r.status, 200);

        await alice.get('/auth/logout');
        await alice.post('/api/auth/login', { email: 'alice@example.com', password: PW });
        r = await alice.post('/api/auth/login/2fa', { recoveryCode: recovery[0] });
        assert.strictEqual(r.status, 401, 'recovery code twice');
        await alice.post('/api/auth/login/cancel');
    });

    await test('passkeys: login options carry a challenge', async () => {
        const r = await client().post('/api/auth/passkey/options', {});
        assert.strictEqual(r.status, 200);
        assert.ok(r.body.challenge);
        assert.strictEqual(r.body.rpId, 'lux.pluginhub.de');
    });

    await test('password reset: link changes the password once, 2FA still applies', async () => {
        const anon = client();
        const before = outbox.length;
        let r = await anon.post('/api/auth/forgot-password', { email: 'unknown@example.com' });
        assert.strictEqual(r.status, 200);
        assert.strictEqual(outbox.length, before);
        r = await anon.post('/api/auth/forgot-password', { email: 'alice@example.com' });
        assert.strictEqual(r.status, 200);
        const token = tokenFrom(outbox[outbox.length - 1]);
        assert.ok(token);
        r = await anon.get(`/api/auth/reset-password/check?token=${token}`);
        assert.strictEqual(r.body.valid, true);
        r = await anon.post('/api/auth/reset-password', { token, password: 'brand new password' });
        assert.strictEqual(r.status, 200);
        r = await anon.post('/api/auth/reset-password', { token, password: 'another new password' });
        assert.strictEqual(r.status, 400);
        r = await anon.post('/api/auth/login', { email: 'alice@example.com', password: PW });
        assert.strictEqual(r.status, 401);
        r = await anon.post('/api/auth/login', { email: 'alice@example.com', password: 'brand new password' });
        assert.strictEqual(r.body.twoFactor, true);
    });

    await test('lockout after repeated wrong passwords', async () => {
        const [res] = await pool.query('UPDATE users SET failed_logins = 7 WHERE username = ?', ['alice']);
        assert.strictEqual(res.affectedRows, 1);
        const x = client();
        let r = await x.post('/api/auth/login', { email: 'alice@example.com', password: 'wrong wrong' });
        assert.strictEqual(r.status, 401);
        r = await x.post('/api/auth/login', { email: 'alice@example.com', password: 'brand new password' });
        assert.strictEqual(r.status, 429);
        assert.strictEqual(r.body.code, 'locked');
        clock += 16 * 60 * 1000;
        r = await x.post('/api/auth/login', { email: 'alice@example.com', password: 'brand new password' });
        assert.strictEqual(r.status, 200);
    });

    await test('quota: daily limit closes registration and refuses reset mails until tomorrow', async () => {
        const p = email._periods(new Date(clock));
        await pool.query('INSERT INTO email_usage (period, sent, blocked) VALUES (?, ?, FALSE) ON CONFLICT (period) DO NOTHING RETURNING period', [p.dayKey, 0]);
        await pool.query('UPDATE email_usage SET sent = ? WHERE period = ?', [email.DAILY_LIMIT, p.dayKey]);
        const x = client();
        let r = await x.get('/api/auth/config');
        assert.strictEqual(r.body.registrationOpen, false);
        assert.strictEqual(r.body.emailReason, 'daily');
        assert.strictEqual(r.body.emailResumesAt, '2026-11-17T00:00:00.000Z');
        r = await x.post('/api/auth/register', { username: 'carol', email: 'carol@example.com', password: PW });
        assert.strictEqual(r.status, 503);
        assert.strictEqual(r.body.code, 'email_unavailable');
        r = await x.post('/api/auth/forgot-password', { email: 'alice@example.com' });
        assert.strictEqual(r.status, 503);
        assert.match(r.body.error, /server problem/);
        // Login keeps working.
        r = await x.post('/api/auth/login', { email: 'alice@example.com', password: 'brand new password' });
        assert.strictEqual(r.status, 200);
    });

    await test('quota: next day it works again; Resend monthly error blocks until the month ends', async () => {
        clock = Date.parse('2026-11-17T08:00:00Z');
        const x = client();
        let r = await x.get('/api/auth/config');
        assert.strictEqual(r.body.registrationOpen, true);
        nextResult = { ok: false, error: 'monthly_quota' };
        r = await x.post('/api/auth/register', { username: 'carol', email: 'carol@example.com', password: PW });
        assert.strictEqual(r.status, 503);
        const [rows] = await pool.query('SELECT id FROM users WHERE username = ?', ['carol']);
        assert.strictEqual(rows.length, 0, 'account without mail is removed again');
        r = await x.get('/api/auth/config');
        assert.strictEqual(r.body.registrationOpen, false);
        assert.strictEqual(r.body.emailReason, 'monthly');
        assert.strictEqual(r.body.emailResumesAt, '2026-12-01T00:00:00.000Z');
        clock = Date.parse('2026-12-01T00:00:05Z');
        r = await x.get('/api/auth/config');
        assert.strictEqual(r.body.registrationOpen, true);
    });

    await test('quota: a failed send is not counted', async () => {
        const p = email._periods(new Date(clock));
        nextResult = { ok: false, error: 'network' };
        const r = await email.sendEmail({ to: 'z@example.com', subject: 's', html: 'h' });
        assert.strictEqual(r.sent, false);
        const [rows] = await pool.query('SELECT sent FROM email_usage WHERE period = ?', [p.dayKey]);
        assert.strictEqual(Number(rows[0].sent), 0);
    });

    await test('form posts from other sites are refused', async () => {
        const r = await new Promise((resolve, reject) => {
            const body = 'email=alice%40example.com&password=x';
            const req = http.request({ host: '127.0.0.1', port, method: 'POST', path: '/api/auth/login',
                headers: { 'Content-Type': 'application/x-www-form-urlencoded', 'Content-Length': Buffer.byteLength(body) } },
            (res) => { res.resume(); res.on('end', () => resolve(res.statusCode)); });
            req.on('error', reject); req.write(body); req.end();
        });
        assert.strictEqual(r, 415);
    });

    await test('rate limit: the sixth registration from one address within an hour is refused', async () => {
        const strict = express();
        strict.use(session({ secret: 'y', resave: false, saveUninitialized: false }));
        strict.use(require(path.join(SITE, 'routes', 'accountAuth.js'))({ pool, email, now: () => clock }));
        const s2 = strict.listen(0);
        await new Promise((r) => s2.once('listening', r));
        const x = new Client(s2.address().port);
        const codes = [];
        for (let i = 0; i < 6; i++) {
            const r = await x.post('/api/auth/register', { username: 'x', email: 'bad', password: 'x' });
            codes.push(r.status);
        }
        s2.close();
        assert.deepStrictEqual(codes, [400, 400, 400, 400, 400, 429]);
    });

    server.close();
    if (failures) {
        console.error(`\n${failures} test(s) failed`);
        process.exit(1);
    }
    console.log('\nall account auth tests passed');
    process.exit(0);
}

main().catch((err) => { console.error(err); process.exit(1); });
