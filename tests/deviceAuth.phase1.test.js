    res = await request(server, { url: `/auth/device?code_challenge=${p1.challenge}&state=${state}&device_name=DESKTOP-TEST&platform=win32` });
    check('angemeldet -> Redirect auf die SPA-Seite', res.status === 302 && res.headers.location.startsWith('/authorize-device?'), res.headers.location);

    res = await approve(server, { challenge: p1.challenge, state });
    check('approve liefert eine luxclient://auth URL', res.status === 200 && String(res.body.redirectUrl).startsWith('luxclient://auth?code='), res.body);
