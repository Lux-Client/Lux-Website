    check('Neuanmeldung eines abgemeldeten Geraets funktioniert', res.status === 200 && Boolean(res.body.accessToken), res.body);
    const accessC = res.body.accessToken;

    res = await request(server, { url: '/api/cloud/me', token: accessC });
    check('neues Token wird akzeptiert', res.status === 200, res.body);

    console.log('     ... warte auf den Ablauf des Access-Tokens (2 s)');
    await sleep(2500);
    res = await request(server, { url: '/api/cloud/me', token: accessC });
    check('abgelaufenes Token -> token_expired', res.status === 401 && res.body.error === 'token_expired', res.body);

    const [devRow] = await pool.query('SELECT refresh_token_hash FROM client_devices WHERE device_uuid = ?', ['dev-aaaaaaaa-1']);
    check('Refresh-Token liegt nur als Hash in der DB',
        devRow[0] && /^[0-9a-f]{64}$/.test(devRow[0].refresh_token_hash), devRow[0]);

    const p6 = pkce();
    res = await approve(server, { challenge: p6.challenge, state });
    const code6 = codeFrom(res.body.redirectUrl);
    res = await request(server, {
        method: 'POST',
        url: '/api/auth/device/token',
        body: { code: code6, code_verifier: p6.verifier, device_uuid: 'dev-aaaaaaaa-1', platform: 'win32' }
    });
    const accessD = res.body.accessToken;

    res = await request(server, { method: 'POST', url: '/api/auth/device/revoke', token: accessD });
    check('revoke -> 200', res.status === 200, res.body);

    res = await request(server, { url: '/api/cloud/me', token: accessD });
    check('nach revoke ist das Token wertlos', res.status === 401 && res.body.error === 'device_revoked', res.body);

    console.log('\n7) Gebannte Konten');
    sessionUser = { id: 2, username: 'bannedguy', role: 'user', banned: false };
    const p7 = pkce();
