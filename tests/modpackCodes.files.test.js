// Eigene Dateien in Modpack-Codes: Mods, die Modrinth und CurseForge nicht kennen, laedt
// der Launcher in den Cloud-Speicher des Kontos. Sie zaehlen gegen dasselbe Limit wie die
// Cloud-Instanzen, lassen sich ueber den Code laden und verschwinden mit dem Code.
const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');

process.env.DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'lux-codefiles-test-'));

const { Harness } = require('./luxcloudHarness');

const h = new Harness();

const sha = (buffer) => crypto.createHash('sha256').update(buffer).digest('hex');

const OWN_MOD = Buffer.from('PK\u0003\u0004 my own mod '.repeat(200));
const OWN_PACK = Buffer.from('PK\u0003\u0004 my own pack '.repeat(100));
const MOD_A = { projectId: 'AANobbMI', versionId: 'v1', fileName: 'sodium-1.jar', title: 'Sodium' };

function exportBody(extra = {}) {
    return {
        name: 'Friends Pack',
        mods: [MOD_A],
        resourcePacks: [],
        shaders: [],
        instanceVersion: '1.21.1',
        instanceLoader: 'fabric',
        ownerUuid: 'mc-uuid-files',
        ...extra
    };
}

async function main() {
    await h.start({
        mount: (app) => require(path.join(__dirname, '..', 'codes_system.js'))(app, 'test-admin-password', h.pool)
    });
    await h.pool.query(`
        CREATE TABLE IF NOT EXISTS modpack_codes (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            code VARCHAR(8) UNIQUE NOT NULL,
            owner_uuid VARCHAR(100),
            owner_ip VARCHAR(45),
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
    `);

    const userId = await h.createUser({ googleId: 'g-files', username: 'creator' });
    const otherId = await h.createUser({ googleId: 'g-other', username: 'other' });
    const userToken = (await h.authorizeDevice({
        user: { id: userId, username: 'creator', role: 'user', banned: false },
        deviceUuid: 'dev-files-0001'
    })).accessToken;
    const otherToken = (await h.authorizeDevice({
        user: { id: otherId, username: 'other', role: 'user', banned: false },
        deviceUuid: 'dev-other-0001'
    })).accessToken;

    const modHash = sha(OWN_MOD);
    const packHash = sha(OWN_PACK);
    let res;

    h.section('1) Ohne Konto keine eigenen Dateien');

    res = await h.request({ method: 'POST', url: '/api/modpack/files/check', body: { files: [] } });
    h.check('Pruefen ohne Anmeldung -> 401', res.status === 401, res.body);
    res = await h.request({ method: 'PUT', url: `/api/modpack/files/${modHash}`, body: OWN_MOD, headers: { 'Content-Type': 'application/octet-stream' } });
    h.check('Hochladen ohne Anmeldung -> 401', res.status === 401, res.body);
    res = await h.request({
        method: 'POST',
        url: '/api/modpack/save',
        body: exportBody({ uploads: [{ sha256: modHash, fileName: 'mymod.jar', kind: 'mod' }] })
    });
    h.check('Export mit eigenen Dateien ohne Konto -> 401', res.status === 401, res.body);

    h.section('2) Speicher pruefen und hochladen');

    res = await h.request({
        method: 'POST',
        url: '/api/modpack/files/check',
        token: userToken,
        body: { files: [{ sha256: modHash, size: OWN_MOD.length, fileName: 'mymod.jar' }, { sha256: packHash, size: OWN_PACK.length }] }
    });
    h.check('Pruefen -> passt, beide fehlen', res.status === 200 && res.body.fits === true && res.body.missing.length === 2, res.body);
    h.check('benoetigt genau beide Groessen', res.body.neededBytes === OWN_MOD.length + OWN_PACK.length, res.body.neededBytes);

    res = await h.request({
        method: 'PUT',
        url: `/api/modpack/files/${modHash}`,
        token: userToken,
        body: Buffer.from('falsche Daten'),
        headers: { 'Content-Type': 'application/octet-stream' }
    });
    h.check('falscher Inhalt -> 400 hash_mismatch', res.status === 400 && res.body.error === 'hash_mismatch', res.body);

    res = await h.request({ method: 'PUT', url: `/api/modpack/files/${modHash}`, token: userToken, body: OWN_MOD, headers: { 'Content-Type': 'application/octet-stream' } });
    h.check('Mod hochgeladen -> 201', res.status === 201 && res.body.size === OWN_MOD.length, res.body);
    res = await h.request({ method: 'PUT', url: `/api/modpack/files/${modHash}`, token: userToken, body: OWN_MOD, headers: { 'Content-Type': 'application/octet-stream' } });
    h.check('nochmal hochladen -> 200, zaehlt nicht doppelt', res.status === 200 && res.body.existing === true, res.body);
    res = await h.request({ method: 'PUT', url: `/api/modpack/files/${packHash}`, token: userToken, body: OWN_PACK, headers: { 'Content-Type': 'application/octet-stream' } });
    h.check('Pack hochgeladen -> 201', res.status === 201, res.body);

    res = await h.request({ url: '/api/modpack/my-uploads', token: userToken });
    h.check('Speicher zeigt beide Dateien', res.status === 200 && res.body.quota.codeFileBytes === OWN_MOD.length + OWN_PACK.length, res.body.quota);

    h.section('3) Fremde Dateien lassen sich nicht in einen Code packen');

    res = await h.request({
        method: 'POST',
        url: '/api/modpack/save',
        token: otherToken,
        body: exportBody({ ownerUuid: 'mc-uuid-other', uploads: [{ sha256: modHash, fileName: 'mymod.jar', kind: 'mod' }] })
    });
    h.check('anderes Konto -> 409', res.status === 409, res.body);

    res = await h.request({
        method: 'POST',
        url: '/api/modpack/save',
        token: userToken,
        body: exportBody({ uploads: [{ sha256: modHash, fileName: '../../evil.sh', kind: 'mod' }] })
    });
    h.check('ungueltiger Dateiname -> 400', res.status === 400, res.body);

    h.section('4) Export mit eigenen Dateien und Import');

    res = await h.request({
        method: 'POST',
        url: '/api/modpack/save',
        token: userToken,
        body: exportBody({
            uploads: [
                { sha256: modHash, fileName: 'mymod-1.0.jar', kind: 'mod', title: 'My Mod' },
                { sha256: packHash, fileName: 'mypack.zip', kind: 'resourcepack' }
            ]
        })
    });
    h.check('Export -> 200 mit 2 Dateien', res.status === 200 && res.body.success && res.body.uploads === 2, res.body);
    const code = res.body.code;

    res = await h.request({ url: `/api/modpack/${code}` });
    const uploads = res.body.data && res.body.data.uploads;
    h.check('Import liefert die eigenen Dateien', Array.isArray(uploads) && uploads.length === 2
        && uploads[0].sha256 === modHash && uploads[0].fileName === 'mymod-1.0.jar' && uploads[0].size === OWN_MOD.length, uploads);

    res = await h.request({ url: `/api/modpack/${code}/files/${modHash}`, raw: true });
    h.check('Download ohne Konto -> genau die Datei', res.status === 200 && Buffer.compare(res.body, OWN_MOD) === 0, res.status);

    res = await h.request({ url: `/api/modpack/${code}/files/${sha(Buffer.from('nope'))}` });
    h.check('Datei, die nicht im Code ist -> 404', res.status === 404, res.body);

    res = await h.request({ url: `/api/modpack/${code}/preview` });
    h.check('Vorschau zeigt Dateien ohne Hash', res.status === 200 && res.body.data.uploads.length === 2 && !('sha256' in res.body.data.uploads[0]), res.body.data.uploads);

    res = await h.request({ url: '/api/modpack/my-uploads', token: userToken });
    const listed = (res.body.codes || []).find((entry) => entry.code === code);
    h.check('Dashboard zeigt den Code mit Dateien', listed && listed.files.length === 2 && listed.filesBytes === OWN_MOD.length + OWN_PACK.length, listed);

    h.section('5) Speicherlimit gilt fuer Instanzen und Code-Dateien zusammen');

    await h.pool.query('UPDATE user_cloud_settings SET quota_bytes = ? WHERE user_id = ?', [OWN_MOD.length + OWN_PACK.length + 100, userId]);
    const bigFile = Buffer.alloc(500, 7);
    res = await h.request({
        method: 'POST',
        url: '/api/modpack/files/check',
        token: userToken,
        body: { files: [{ sha256: sha(bigFile), size: bigFile.length }] }
    });
    h.check('passt nicht mehr -> fits false', res.status === 200 && res.body.fits === false, res.body);
    res = await h.request({ method: 'PUT', url: `/api/modpack/files/${sha(bigFile)}`, token: userToken, body: bigFile, headers: { 'Content-Type': 'application/octet-stream' } });
    h.check('Hochladen ueber dem Limit -> 413 quota_exceeded', res.status === 413 && res.body.error === 'quota_exceeded', res.body);

    h.section('6) Code loeschen gibt den Speicher frei');

    res = await h.request({ method: 'DELETE', url: `/api/modpack/my-codes/${code}`, token: otherToken });
    h.check('fremdes Konto darf nicht loeschen -> 403', res.status === 403, res.body);

    res = await h.request({ method: 'DELETE', url: `/api/modpack/my-codes/${code}`, token: userToken });
    h.check('Besitzer loescht -> 200, Speicher frei', res.status === 200 && res.body.quota.codeFileBytes === 0, res.body);
    res = await h.request({ url: `/api/modpack/${code}/files/${modHash}` });
    h.check('Download danach -> 404', res.status === 404, res.body);
    const storedFile = path.join(h.storageRoot, 'blobs', 'codefiles', modHash.slice(0, 2), modHash.slice(2, 4), modHash);
    h.check('Datei liegt nicht mehr im Speicher', !fs.existsSync(storedFile), storedFile);

    h.section('7) Abgelaufene Codes nehmen ihre Dateien mit');

    await h.pool.query('UPDATE user_cloud_settings SET quota_bytes = ? WHERE user_id = ?', [5 * 1024 * 1024 * 1024, userId]);
    res = await h.request({ method: 'PUT', url: `/api/modpack/files/${modHash}`, token: userToken, body: OWN_MOD, headers: { 'Content-Type': 'application/octet-stream' } });
    res = await h.request({
        method: 'POST',
        url: '/api/modpack/save',
        token: userToken,
        body: exportBody({ uploads: [{ sha256: modHash, fileName: 'mymod-1.0.jar', kind: 'mod' }] })
    });
    const expiring = res.body.code;
    h.check('neuer Code mit Datei', res.status === 200 && res.body.uploads === 1, res.body);
    const codeFile = path.join(process.env.DATA_DIR, 'codes', `${expiring}.json`);
    const old = new Date(Date.now() - 8 * 24 * 60 * 60 * 1000);
    fs.utimesSync(codeFile, old, old);

    const codeFiles = require(path.join(__dirname, '..', 'codeFiles.js'));
    // Die Aufraeumrunde laeuft beim Start und stuendlich; hier direkt anstossen.
    const codesSystemPath = require.resolve(path.join(__dirname, '..', 'codes_system.js'));
    delete require.cache[codesSystemPath];
    const fakeApp = { get() {}, post() {}, put() {}, patch() {}, delete() {} };
    require(codesSystemPath)(fakeApp, 'x', h.pool);
    for (let i = 0; i < 40; i += 1) {
        if (!fs.existsSync(codeFile) && await codeFiles.codeFileBytes(userId, h.pool) === 0) break;
        await new Promise((r) => setTimeout(r, 50));
    }
    h.check('abgelaufener Code ist weg', !fs.existsSync(codeFile), codeFile);
    h.check('seine Datei zaehlt nicht mehr', await codeFiles.codeFileBytes(userId, h.pool) === 0);

    h.section('8) Hochgeladen, aber nie in einem Code: wird aufgeraeumt');

    res = await h.request({ method: 'PUT', url: `/api/modpack/files/${packHash}`, token: userToken, body: OWN_PACK, headers: { 'Content-Type': 'application/octet-stream' } });
    await h.pool.query(`UPDATE modpack_code_blobs SET created_at = NOW() - INTERVAL '2 days' WHERE user_id = ?`, [userId]);
    const pruned = await codeFiles.pruneStaleUploads(h.pool);
    h.check('verwaiste Datei entfernt', pruned.removed === 1 && await codeFiles.codeFileBytes(userId, h.pool) === 0, pruned);
}

main()
    .catch((err) => {
        console.error(err);
        h.failed += 1;
    })
    .finally(() => {
        try { fs.rmSync(process.env.DATA_DIR, { recursive: true, force: true }); } catch { /* ignore */ }
        h.finish();
    });
